"""
Классификация вопросов для LLM сервера
Без зависимостей от FastAPI - для тестирования
"""


def classify_question(text: str) -> str:
    """
    Классифицирует вопрос по типу: experience / technical / general
    """
    text_lower = text.lower()
    
    experience_keywords = [
        'опыт', 'работал', 'работали', 'проект', 'проекты', 'делал', 'делали',
        'команда', 'команде', 'задача', 'задачи', 'ситуация', 'ситуации',
        'пример', 'примеры', 'как вы', 'расскажите о себе', 'почему вы',
        'ваш опыт', 'вашем опыте', 'последний проект', 'достижения',
        'опишите', 'решили', 'сложную', 'справились', 'столкнулись'
    ]
    
    technical_keywords = [
        'что такое', 'как работает', 'объясни', 'объясните', 'разница между',
        'чем отличается', 'чем отличаются', 'в чем разница', 'сравни', 'сравните',
        'плюсы и минусы', 'преимущества', 'недостатки', 'принцип', 'алгоритм',
        'структура данных', 'структуры данных', 'паттерн', 'паттерны',
        'зачем нужен', 'зачем нужны', 'когда использовать', 'определение',
        'list', 'tuple', 'set', 'dict', 'словарь', 'кортеж', 'список', 'множество',
        'индекс', 'индексы', 'транзакция', 'транзакции', 'acid', 'rest', 'api',
        'grpc', 'docker', 'kubernetes', 'async', 'await', 'gil', 'gc', 'solid'
    ]
    
    exp_score = sum(1 for kw in experience_keywords if kw in text_lower)
    tech_score = sum(1 for kw in technical_keywords if kw in text_lower)
    
    if exp_score > tech_score and exp_score > 0:
        return 'experience'
    elif tech_score > exp_score and tech_score > 0:
        return 'technical'
    else:
        return 'general'


def get_max_tokens_for_type(question_type: str) -> int:
    """Возвращает рекомендуемое количество токенов по типу вопроса (краткие тезисы)"""
    return {
        'experience': 250,   # Опорные тезисы STAR
        'technical': 220,    # Определение + механизм + нюанс
        'general': 180       # Сверхкраткие тезисы
    }.get(question_type, 200)


def get_temperature_for_type(question_type: str) -> float:
    """Возвращает рекомендуемую temperature по типу вопроса"""
    return {
        'experience': 0.7,   # Опыт и кейсы
        'technical': 0.4,    # Точные технические определения
        'general': 0.6
    }.get(question_type, 0.6)


def build_contextual_prompt(question_type: str, user_context: str, profile: str = 'job_interview_ru') -> str:
    """
    Строит краткий опорный промпт в зависимости от типа вопроса и профиля.
    Для собеседований использует телеграфные опорные пункты, для других - системный промпт из профиля.
    """
    # Для профилей не собеседований используем системный промпт из prompts.py
    if profile in ['business_meeting', 'daily_sync', 'presentation', 'custom']:
        from prompts import get_system_prompt
        return get_system_prompt(profile, user_context)
    
    # Разделяем резюме и вакансию если они объединены
    resume_part = user_context
    vacancy_part = ''
    if '## Вакансия:' in user_context:
        parts = user_context.split('## Вакансия:', 1)
        resume_part = parts[0].strip()
        vacancy_part = parts[1].strip() if len(parts) > 1 else ''
    
    if question_type == 'experience':
        context_full = resume_part[:2000] if resume_part else ''
        vacancy_info = f'\n\n## Вакансия (подчёркивай релевантный опыт):\n{vacancy_part[:500]}' if vacancy_part else ''
        return (
            'Ты AI-ассистент для технических собеседований. Дай краткий структурированный ответ.\n\n'
            '## ВАЖНО: Отвечай строго на ПОСЛЕДНИЙ вопрос интервьюера!\n\n'
            '## Инструкция по структуре ответа (3-4 емких пункта по STAR):\n'
            '- Ситуация и контекст: проект, технологии и масштаб задачи\n'
            '- Задача: цель и возникшая сложность\n'
            '- Решение: предпринятые действия и инструменты\n'
            '- Результат: измеримый эффект или метрика\n\n'
            '## Правила:\n'
            '- Опирайся только на факты и технологии из резюме кандидата\n'
            '- Запрещено выводить шаблонные подзаголовки (например "Главный тезис", "Резюме")\n'
            '- Пиши сразу готовые тезисы по существу\n\n'
            f'## Резюме кандидата:\n{context_full}'
            f'{vacancy_info}'
        )
    elif question_type == 'technical':
        context_short = resume_part[:500] if resume_part else ''
        candidate_block = (
            f'\n\n## Контекст и стек кандидата (используй для релевантных примеров):\n{context_short}'
            if context_short
            else ''
        )
        return (
            'Ты AI-ассистент для технических собеседований. Даёшь точную экспертную шпаргалку.\n\n'
            '## ВАЖНО: Отвечай строго на ПОСЛЕДНИЙ вопрос интервьюера!\n\n'
            '## Инструкция по структуре ответа (3-4 четких пункта):\n'
            '- Определение и ключевая концепция\n'
            '- Внутренний механизм работы или ключевые различия\n'
            '- Где и как применяется на практике\n'
            '- Подводный камень, компромисс или частая ошибка\n\n'
            '## Правила:\n'
            '- Отвечай строго по теме вопроса, не подменяй тему посторонними историями\n'
            '- Запрещено выводить служебные подписи секций (например "Главный тезис", "Резюме")\n'
            '- Сразу формулируй суть ответа'
            f'{candidate_block}'
        )
    else:
        context_short = resume_part[:800] if resume_part else ''
        return (
            'Ты AI-ассистент для собеседований и профессиональных встреч.\n\n'
            '## ВАЖНО: Отвечай строго на ПОСЛЕДНИЙ вопрос!\n\n'
            '## Инструкция по структуре ответа (3 емких тезиса):\n'
            '- Суть ответа на вопрос\n'
            '- Практический аргумент или ключевой факт\n'
            '- Резюме или рекомендация к действию\n\n'
            '## Правила:\n'
            '- Отвечай кратко и конкретно\n'
            '- Запрещено выводить служебные подписи (например "Главный тезис", "Резюме")\n'
            '- Сразу формулируй готовые опорные тезисы\n\n'
            f'## Контекст кандидата:\n{context_short}'
        )
